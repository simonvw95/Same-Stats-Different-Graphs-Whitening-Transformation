def upload_image(event):

    global current_dataset

    file = event.target.files.item(0)

    if file is None:
        return

    reader = FileReader.new()

    n_points = int(
        document.getElementById(
            "parameter"
        ).value
    )

    def onload(evt):

        global current_dataset

        data = bytes(
            reader.result.to_py()
        )

        image = Image.open(
            io.BytesIO(data)
        )

        # Process image
        result = process_image(
            image,
            n_points
        )

        # Store dataset globally
        current_dataset = result["dataset"]

        # Enable transform button
        transform_button = document.getElementById(
            "transform-button"
        )

        # ====================================================
        # DISPLAY ORIGINAL IMAGE
        # ====================================================

        img1 = document.getElementById(
            "processed-image"
        )

        img1.src = URL.createObjectURL(
            file
        )

        img1.style.display = "block"

        # ====================================================
        # DISPLAY SCATTER + STATISTICS
        # ====================================================

        img2 = document.getElementById(
            "scatter-image"
        )

        img2.src = (
            "data:image/png;base64,"
            + result["figure"]
        )

        img2.style.display = "block"

        print(
            "Image successfully processed."
        )

        print(
            "Dataset contains",
            len(current_dataset),
            "points."
        )

    reader.onload = onload

    reader.readAsArrayBuffer(file)



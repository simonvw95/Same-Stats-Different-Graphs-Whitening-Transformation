# SCRIPT 2: LINEAR STATISTICAL TRANSFORMATION
# ============================================================

def project_statistics(
    coords,
    t_xm=54.265,
    t_ym=47.835,
    t_xsd=16.765,
    t_ysd=26.935,
    t_pc=-0.065,
    eps=1e-8
):

    # Make sure coords is a NumPy float array
    coords = np.asarray(
        coords,
        dtype=np.float64
    )

    # --------------------------------------------------------
    # Center current scatterplot
    # --------------------------------------------------------

    mean = coords.mean(
        axis=0,
        keepdims=True
    )

    X = coords - mean

    # --------------------------------------------------------
    # Current covariance matrix
    # --------------------------------------------------------

    cov = np.cov(
        X,
        rowvar=False
    )

    # --------------------------------------------------------
    # Target covariance matrix
    # --------------------------------------------------------

    target_cov = np.array([
        [
            t_xsd ** 2,
            t_pc * t_xsd * t_ysd
        ],
        [
            t_pc * t_xsd * t_ysd,
            t_ysd ** 2
        ]
    ], dtype=np.float64)

    # --------------------------------------------------------
    # Whitening transformation
    # --------------------------------------------------------

    eigvals, eigvecs = np.linalg.eigh(
        cov + eps * np.eye(2)
    )

    W = (
        eigvecs
        @ np.diag(
            1.0 / np.sqrt(eigvals)
        )
        @ eigvecs.T
    )

    # --------------------------------------------------------
    # Coloring transformation
    # --------------------------------------------------------

    teigvals, teigvecs = np.linalg.eigh(
        target_cov
    )

    C = (
        teigvecs
        @ np.diag(
            np.sqrt(teigvals)
        )
        @ teigvecs.T
    )

    # --------------------------------------------------------
    # Apply whitening + coloring
    # --------------------------------------------------------

    X_proj = (
        (X @ W.T)
        @ C.T
    )

    # --------------------------------------------------------
    # Apply target mean
    # --------------------------------------------------------

    X_proj += np.array([
        t_xm,
        t_ym
    ])

    return X_proj



def process_image(image, N):

    cv_image = cv2.cvtColor(
        np.array(image),
        cv2.COLOR_RGB2BGR
    )

    img_gray = cv2.cvtColor(
        cv_image,
        cv2.COLOR_BGR2GRAY
    )

    # Apply binary thresholding
    ret, thresh = cv2.threshold(
        img_gray,
        150,
        255,
        cv2.THRESH_BINARY
    )

    # Get coordinates of black/light-gray areas
    coordinates = np.column_stack(
        np.where(thresh == 0)
    )

    # Randomly sample N points
    idx = np.random.choice(
        len(coordinates),
        N,
        replace=False
    )

    selected_coords = coordinates[idx]

    # Compute centroid
    cx, cy = selected_coords.mean(axis=0)

    # Translate to origin
    X0 = selected_coords - np.array([cx, cy])

    # Apply 90° clockwise rotation
    R = np.array([
        [0, 1],
        [-1, 0]
    ])

    selected_coords = X0 @ R.T

    # Normalize per axis
    mins = selected_coords.min(axis=0)
    maxs = selected_coords.max(axis=0)

    ranges = maxs - mins
    ranges[ranges == 0] = 1

    # Convert to DataFrame
    df = pd.DataFrame(selected_coords)

    df.rename(
        columns={
            0: "x",
            1: "y"
        },
        inplace=True
    )

    # ========================================================
    # CREATE ORIGINAL SCATTER + STATISTICS FIGURE
    # ========================================================

    res = get_values(df)

    fs = 15

    labels = [
        "X Mean",
        "Y Mean",
        "X SD",
        "Y SD",
        "Corr."
    ]

    max_label_length = max(
        len(la)
        for la in labels
    )

    # Find plot limits
    min_x, min_y = (
        np.min(df.to_numpy(), axis=0) - 15
    )

    max_x, max_y = (
        np.max(df.to_numpy(), axis=0) + 15
    )

    default_min = -25
    default_max = 125

    # Increase margins while preserving square axes
    while True:

        if (
            min_x <= default_min
            or min_y <= default_min
            or max_x >= default_max
            or max_y >= default_max
        ):
            default_min -= 5
            default_max += 5
        else:
            break

    # Create figure
    fig = plt.figure(
        figsize=(7, 3),
        constrained_layout=True
    )

    gs = fig.add_gridspec(
        1,
        2,
        width_ratios=[1, 0.8]
    )

    # ========================================================
    # LEFT AXIS: SCATTERPLOT
    # ========================================================

    ax = fig.add_subplot(gs[0, 0])

    # sns.regplot(
        # x="x",
        # y="y",
        # data=df,
        # ci=None,
        # fit_reg=False,
        # scatter_kws={
            # "s": 4,
            # "alpha": 0.9,
            # "color": "black"
        # },
        # ax=ax
    # )
    
    ax.scatter(df["x"],
    df["y"],
    s=4,
    alpha=0.9,
    color="black"
    )

    ax.set_xlim(
        default_min,
        default_max
    )

    ax.set_ylim(
        default_min,
        default_max
    )

    ax.set_aspect(
        "equal",
        adjustable="box"
    )

    # ========================================================
    # RIGHT AXIS: STATISTICS
    # ========================================================

    ax_text = fig.add_subplot(
        gs[0, 1]
    )

    ax_text.axis("off")

    y_positions = [
        0.9,
        0.75,
        0.60,
        0.45,
        0.30
    ]

    # Shadow text
    for i, (label, value) in enumerate(
        zip(labels, res)
    ):

        ax_text.text(
            0.0,
            y_positions[i],
            label.ljust(max_label_length)
            + ": "
            + format(value, "0.9f")[:-2],
            fontsize=fs,
            alpha=0.3,
            transform=ax_text.transAxes
        )

    # Main text
    for i, (label, value) in enumerate(
        zip(labels, res)
    ):

        ax_text.text(
            0.0,
            y_positions[i],
            label.ljust(max_label_length)
            + ": "
            + format(value, "0.9f")[:-7],
            fontsize=fs,
            alpha=1,
            transform=ax_text.transAxes
        )

    # Convert figure to PNG/base64
    fig.canvas.draw()

    buf = np.asarray(
        fig.canvas.buffer_rgba()
    )

    plt.close(fig)

    figure = Image.fromarray(buf)

    return {
        "dataset": df,
        "figure": pil_to_base64(figure)
    }


